def resources_for_skill(skill: str) -> list[dict]:
    """Return resources for a single skill."""
    matches = [r for r in CATALOG if r.skill.lower() == skill.lower()]
    return [asdict(r) for r in sorted(matches, key=lambda r: r.rating or 0, reverse=True)]


def resources_for_skills(skills: list[str]) -> dict[str, list[dict]]:
    """Return a mapping of skill -> resources."""
    return {skill: resources_for_skill(skill) for skill in skills}
